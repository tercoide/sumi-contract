def main(path):
    txt = open(path, encoding='utf-8').read()
    missing = []
    def fill(m):
        sid = ''.join(re.findall(r'"(.*)"', m.group(2)))
        cur = ''.join(re.findall(r'"(.*)"', m.group(3)))
        if not sid or cur:
            return m.group(0)
        if sid in ES:
            return '%smsgid %smsgstr "%s"\n' % (m.group(1), m.group(2), ES[sid])
        missing.append(sid)
        return m.group(0)
    txt = re.sub(r'((?:#.*\n)*)msgid ((?:".*"\n)+)msgstr ((?:".*"\n)+)', fill, txt)
    open(path, 'w', encoding='utf-8').write(txt)
    for s in missing:
        print('NOT TRANSLATED:', s)

